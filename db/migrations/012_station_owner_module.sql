-- =============================================================================
-- Script : 012_station_owner_module.sql
-- Purpose: Adds the Station Owner Module columns to the existing 'stations' and
--          'connectors' tables, and creates the 'status_logs' table.
--
-- Rules  : ADDITIVE ONLY — no DROP, RENAME, DELETE, UPDATE of existing data,
--          no changing existing column types.
--          Idempotent: safe to run more than once (IF NOT EXISTS / DO blocks).
--
-- Affects:
--   stations   — 7 new nullable/defaulted columns + 1 index + 1 check constraint
--   connectors — 3 new nullable/defaulted columns + 2 check constraints
--   status_logs — new table + 1 index
-- =============================================================================

BEGIN;

-- ─────────────────────────────────────────────────────────────────────────────
-- 1. Extend 'stations' table with owner-module columns
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE stations
    ADD COLUMN IF NOT EXISTS owner_id    integer       NULL
        REFERENCES users(id) ON DELETE RESTRICT,
    ADD COLUMN IF NOT EXISTS type        varchar(10)   NOT NULL DEFAULT 'B2P',
    ADD COLUMN IF NOT EXISTS open_time   time          NULL,
    ADD COLUMN IF NOT EXISTS close_time  time          NULL,
    ADD COLUMN IF NOT EXISTS rating      numeric(3,2)  NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS is_active   boolean       NOT NULL DEFAULT true,
    ADD COLUMN IF NOT EXISTS updated_at  timestamptz   NULL;

-- CHECK constraint on type (idempotent — only added if not already present)
DO $$ BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'chk_stations_type'
          AND conrelid = 'public.stations'::regclass
    ) THEN
        ALTER TABLE stations
            ADD CONSTRAINT chk_stations_type CHECK (type IN ('P2P', 'B2P'));
    END IF;
END $$;

-- Index on owner_id for FK lookups
CREATE INDEX IF NOT EXISTS idx_stations_owner_id ON stations (owner_id);

-- ─────────────────────────────────────────────────────────────────────────────
-- 2. Extend 'connectors' table with owner-module / charging-point columns
-- ─────────────────────────────────────────────────────────────────────────────

ALTER TABLE connectors
    ADD COLUMN IF NOT EXISTS label          varchar(50)   NULL,
    ADD COLUMN IF NOT EXISTS price_per_kwh  numeric(10,2) NULL,
    ADD COLUMN IF NOT EXISTS is_active      boolean       NOT NULL DEFAULT true;

-- CHECK: power_kw must be positive (idempotent)
DO $$ BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'chk_connectors_power_kw_positive'
          AND conrelid = 'public.connectors'::regclass
    ) THEN
        ALTER TABLE connectors
            ADD CONSTRAINT chk_connectors_power_kw_positive CHECK (power_kw > 0);
    END IF;
END $$;

-- CHECK: price_per_kwh must be non-negative (idempotent)
DO $$ BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'chk_connectors_price_per_kwh_non_negative'
          AND conrelid = 'public.connectors'::regclass
    ) THEN
        ALTER TABLE connectors
            ADD CONSTRAINT chk_connectors_price_per_kwh_non_negative
                CHECK (price_per_kwh >= 0);
    END IF;
END $$;

-- ─────────────────────────────────────────────────────────────────────────────
-- 3. Create 'status_logs' table
-- ─────────────────────────────────────────────────────────────────────────────

CREATE TABLE IF NOT EXISTS status_logs (
    id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    point_id             integer      NOT NULL
        REFERENCES connectors(id) ON DELETE RESTRICT,
    old_status           varchar(20)  NULL,
    new_status           varchar(20)  NOT NULL,
    changed_at           timestamptz  NOT NULL DEFAULT now(),
    changed_by_user_id   integer      NULL
        REFERENCES users(id) ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_status_logs_point_id_changed_at
    ON status_logs (point_id, changed_at);

COMMIT;
